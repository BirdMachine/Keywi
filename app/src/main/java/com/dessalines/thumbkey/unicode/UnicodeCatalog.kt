package com.dessalines.thumbkey.unicode

import android.content.Context
import java.io.InputStream
import java.lang.ref.SoftReference
import java.util.Locale
import java.util.zip.GZIPInputStream
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.sync.Mutex
import kotlinx.coroutines.sync.withLock
import kotlinx.coroutines.withContext

data class UnicodeCategory(val id: String, val label: String)

object UnicodeCategories {
    val groups = listOf(
        UnicodeCategory("all", "All characters"),
        UnicodeCategory("symbols", "Symbols"),
        UnicodeCategory("punctuation", "Punctuation"),
        UnicodeCategory("letters", "Letters & scripts"),
        UnicodeCategory("numbers", "Numbers"),
        UnicodeCategory("marks", "Combining marks"),
        UnicodeCategory("separators", "Spaces & separators"),
        UnicodeCategory("other", "Controls & format"),
    )
}

data class UnicodeEntry(
    val codePoint: Int,
    val name: String,
    val block: String,
    val category: String,
    val aliases: List<String> = emptyList(),
) {
    val text: String get() = String(Character.toChars(codePoint))
    val codePointLabel: String get() = "U+" + codePoint.toString(16).uppercase(Locale.ROOT).padStart(4, '0')
    val displayName: String get() = name
    val groupId: String
        get() = when (category.first()) {
            'L' -> "letters"
            'M' -> "marks"
            'N' -> "numbers"
            'P' -> "punctuation"
            'S' -> "symbols"
            'Z' -> "separators"
            else -> "other"
        }
    val isInvisible: Boolean get() = category.first() == 'C' || category.first() == 'Z'
    val isCombining: Boolean get() = category.first() == 'M'
}

/** A pinned catalog; character names never depend on the phone's older ICU database. */
class UnicodeCatalog(val version: String, val entries: List<UnicodeEntry>) {
    val blocks: List<String> = entries.map { it.block }.distinct().sorted()

    /** Call from Dispatchers.Default. Return a bounded page, never a giant filtered UI list. */
    fun search(
        query: String,
        categoryId: String = "all",
        block: String? = null,
        limit: Int = 240,
        offset: Int = 0,
        ensureActive: () -> Unit = {},
    ): List<UnicodeEntry> {
        require(limit in 1..1000) { "Page size must be between 1 and 1000" }
        require(offset >= 0) { "Offset must not be negative" }
        val trimmed = query.trim().take(200)
        val exactCodePoint = parseCodePoint(trimmed)
        val literalCodePoint = trimmed.takeIf { it.codePointCount(0, it.length) == 1 }?.codePointAt(0)
        val terms = trimmed.split(Regex("\\s+")).filter { it.isNotEmpty() }
        var inspected = 0
        val matches = entries.asSequence().filter { entry ->
            if (inspected++ % 256 == 0) ensureActive()
            (categoryId == "all" || entry.groupId == categoryId) &&
                (block == null || entry.block == block) &&
                when {
                    exactCodePoint != null -> entry.codePoint == exactCodePoint
                    literalCodePoint != null && entry.codePoint == literalCodePoint -> true
                    else -> terms.all { term ->
                        entry.name.contains(term, ignoreCase = true) ||
                            entry.block.contains(term, ignoreCase = true) ||
                            entry.category.equals(term, ignoreCase = true) ||
                            entry.groupId.contains(term, ignoreCase = true) ||
                            entry.aliases.any { it.contains(term, ignoreCase = true) }
                    }
                }
        }
        return matches.drop(offset).take(limit).toList()
    }

    companion object {
        fun parseCodePoint(query: String): Int? {
            val value = when {
                query.startsWith("U+", ignoreCase = true) -> query.substring(2)
                query.startsWith("0x", ignoreCase = true) -> query.substring(2)
                query.length in 4..6 && query.any { it.isDigit() } -> query
                else -> return null
            }
            if (value.isEmpty() || value.length > 6 || value.any { it.digitToIntOrNull(16) == null }) return null
            return value.toIntOrNull(16)?.takeIf { it in 0..0x10FFFF && it !in 0xD800..0xDFFF }
        }

        /** The caller owns [input]; data is generated by scripts/unicode/generate_catalog.py. */
        fun readGzip(input: InputStream): UnicodeCatalog {
            val shared = HashMap<String, String>()
            fun sharedValue(value: String): String = shared.getOrPut(value) { value }
            val result = ArrayList<UnicodeEntry>(173000)
            val reader = GZIPInputStream(input).bufferedReader(Charsets.UTF_8)
            val header = requireNotNull(reader.readLine()) { "Missing Unicode catalog header" }
            require(header.startsWith("# Keywi Unicode ")) { "Invalid Unicode catalog header" }
            val version = header.removePrefix("# Keywi Unicode ")
            reader.forEachLine { line ->
                if (line.isNotEmpty()) {
                    val fields = line.split('\t', limit = 5)
                    require(fields.size == 5) { "Invalid Unicode catalog row" }
                    val cp = fields[0].toInt(16)
                    require(cp in 0..0x10FFFF && cp !in 0xD800..0xDFFF)
                    require(result.isEmpty() || cp > result.last().codePoint) { "Catalog must be sorted and unique" }
                    result.add(
                        UnicodeEntry(
                            codePoint = cp,
                            name = fields[1],
                            category = sharedValue(fields[2]),
                            block = sharedValue(fields[3]),
                            aliases = if (fields[4].isEmpty()) emptyList() else fields[4].split('|'),
                        ),
                    )
                }
            }
            return UnicodeCatalog(version, result)
        }
    }
}

object UnicodeLibraryRepository {
    const val ASSET_PATH = "unicode/catalog.tsv.gz"
    private val mutex = Mutex()
    @Volatile private var cached = SoftReference<UnicodeCatalog>(null)

    suspend fun load(context: Context): UnicodeCatalog = cached.get() ?: withContext(Dispatchers.IO) {
        mutex.withLock {
            cached.get() ?: context.applicationContext.assets.open(ASSET_PATH).use {
                UnicodeCatalog.readGzip(it)
            }.also { cached = SoftReference(it) }
        }
    }
}
